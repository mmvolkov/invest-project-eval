function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

const ACCENT = '1F6FEB';
const P = (text, opts = {}) => new Paragraph({ children: Array.isArray(text) ? text : [new TextRun({ text, ...opts })], spacing: { after: 120, line: 300 }, alignment: opts.align });
