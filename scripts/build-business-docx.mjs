function Figure(name, caption, { maxH = 760 } = {}) {
  const file = img(name);
  const { w, h } = pngSize(file);
  let width = CONTENT_PX;
  let height = Math.round((h / w) * width);
  if (height > maxH) {
    height = maxH;
    width = Math.round((w / h) * height);
  }
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 }, children: [new ImageRun({ type: 'png', data: fs.readFileSync(file), transformation: { width, height } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: [new TextRun({ text: caption, italics: true, size: 18, color: '51606F' })] }),
  ];
}

function Tbl(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map((w) => Math.round((w / total) * CONTENT_W));
  const cell = (text, i, head = false) =>
    new TableCell({
      width: { size: cols[i], type: WidthType.DXA },
      shading: head ? { type: ShadingType.CLEAR, fill: 'E8F0FE', color: 'auto' } : undefined,
      margins: { top: 60, bottom: 60, left: 100, right: 100 },
      children: [new Paragraph({ children: [new TextRun({ text: String(text), bold: head, size: 19 })], spacing: { after: 0, line: 276 } })],
    });
  return new Table({
    width: { size: CONTENT_W, type: WidthType.DXA },
    columnWidths: cols,
    rows: [new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, i, true)) }), ...rows.map((r) => new TableRow({ children: r.map((c, i) => cell(c, i)) }))],
  });
}

